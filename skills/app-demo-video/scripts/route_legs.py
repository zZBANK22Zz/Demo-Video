#!/usr/bin/env python3
"""Turns a route into a Maestro subflow that drives the device along it at a steady pace.

Usage:
  route_legs.py <route.json> <out.yaml> [--step-m 15] [--pause-ms 650] [--end LAT,LNG]
                [--pause-flow ../lib/pause.yaml]

route.json: a JSON array of points, either [[lat, lng], ...] or [{"lat":..,"lng":..}, ...]
            — e.g. the decoded polyline your backend / Google Directions returns.
--end:      final point to land on exactly (e.g. the booking's pickup/dropoff, which is
            usually the place's coordinate, a little off the road). It is appended to the
            route BEFORE pacing, so the last stretch is driven, not jumped.
--mark-every N --mark-prefix NAME:  report a mark (NAME_1, NAME_2, …) every N steps, so the
            edit can start a step mid-leg (needs flows/lib/mark.js and the mark server).
--app-id:   your app's id (same as the calling flow).

Why this exists (see references/lessons.md):
- Maestro `travel` ignores its speed on iOS; a 1.4 km leg took 5+ minutes.
- Bare `setLocation` steps run ~0.3 s apart, so coarse points look like 240 km/h and the
  app's map/route logic cannot keep up. Even spacing + a pause per step = believable speed.
- Never jump: a teleport mid-route makes navigation apps reroute, and the reroute from an
  arbitrary point (one-way streets!) can disagree with what you drive next.
"""
import argparse
import json
from math import asin, cos, radians, sin, sqrt


def km(a, b):
    dlat, dlng = radians(b[0] - a[0]), radians(b[1] - a[1])
    h = sin(dlat / 2) ** 2 + cos(radians(a[0])) * cos(radians(b[0])) * sin(dlng / 2) ** 2
    return 2 * 6371 * asin(sqrt(h))


def evenly(path, n):
    cum = [0.0]
    for a, b in zip(path, path[1:]):
        cum.append(cum[-1] + km(a, b))
    out, j = [], 0
    for i in range(n):
        target = cum[-1] * i / (n - 1)
        while j < len(cum) - 2 and cum[j + 1] < target:
            j += 1
        span = cum[j + 1] - cum[j] or 1
        t = (target - cum[j]) / span
        a, b = path[j], path[j + 1]
        out.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("route")
    ap.add_argument("out")
    ap.add_argument("--step-m", type=float, default=15)
    ap.add_argument("--pause-ms", type=int, default=650)
    ap.add_argument("--end")
    ap.add_argument("--pause-flow", default="../lib/pause.yaml")
    ap.add_argument("--app-id", default="com.example.app")
    ap.add_argument("--mark-every", type=int, default=0)
    ap.add_argument("--mark-prefix", default="leg")
    ap.add_argument("--mark-js", default="../lib/mark.js")
    a = ap.parse_args()

    raw = json.load(open(a.route))
    path = [(p["lat"], p["lng"]) if isinstance(p, dict) else (p[0], p[1]) for p in raw]
    if a.end:
        path.append(tuple(float(v) for v in a.end.split(",")))
    length_m = sum(km(x, y) for x, y in zip(path, path[1:])) * 1000
    points = evenly(path, max(2, round(length_m / a.step_m) + 1))

    lines = ["# Generated by route_legs.py — regenerate, do not edit.", f"appId: {a.app_id}", "---"]
    for i, (lat, lng) in enumerate(points, 1):
        lines += ["- setLocation:", f'    latitude: "{lat:.7f}"', f'    longitude: "{lng:.7f}"']
        if a.mark_every and i % a.mark_every == 0:
            lines.append(f"- runScript: {{ file: {a.mark_js}, env: {{ MARK: {a.mark_prefix}_{i // a.mark_every} }} }}")
        if a.pause_ms:
            lines.append(f"- runFlow: {{ file: {a.pause_flow}, env: {{ PAUSE_MS: {a.pause_ms} }} }}")
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"route_legs: {len(points)} steps over {length_m:.0f} m → {a.out}")


if __name__ == "__main__":
    main()
